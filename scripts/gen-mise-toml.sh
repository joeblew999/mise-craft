#!/usr/bin/env bash
# Writes mise.toml for the Craft apps below. To change a version or add an app, edit the list and
# regenerate:
#   scripts/gen-mise-toml.sh > mise.toml && mise lock
set -euo pipefail

# app id, pinned version, name
apps=(
  "cadcraft 0.13.0 CADCraft"
  "deckcraft 0.11.1 DeckCraft"
  "designcraft 0.13.0 DesignCraft"
  "effectcraft 0.17.0 EffectCraft"
  "figcraft 0.11.2 FigCraft"
  "filmcraft 0.13.0 FilmCraft"
  "gridcraft 0.12.1 GridCraft"
  "lightcraft 0.14.0 LightCraft"
  "pdfcraft 0.14.0 PdfCraft"
  "photocraft 0.16.0 PhotoCraft"
  "soundcraft 0.13.1 SoundCraft"
  "vectorcraft 0.17.0 VectorCraft"
  "wordcraft 0.11.0 WordCraft"
)

cat <<'EOF'
# Generated by scripts/gen-mise-toml.sh: edit that, then regenerate.
#
# Each Craft app's GitHub repo is installed twice under aliases: `<app>-cli` (the CLI, with its MCP
# server) and `<app>` (the desktop app). Each alias gets its own install directory. macOS only for
# now: it's the one platform every app publishes a CLI for.
#
# Every app is listed, but nothing downloads until you name it: `mise run cadcraft:install`.
# (A bare `mise install` still installs them all.)

[settings]
# Don't install missing tools behind your back: not when .mcp.json starts a server with
# `mise exec`, not on `mise run`, and not when a shell can't find a command.
exec_auto_install = false
task.run_auto_install = false
not_found_auto_install = false

[tool_alias]
EOF
for a in "${apps[@]}"; do
  read -r id _ _ <<<"$a"
  printf '%s-cli = "github:storytold/%s"\n%s = "github:storytold/%s"\n' "$id" "$id" "$id" "$id"
done

printf '\n[tools]\njq = "1.8.2" # for the desktop:* tasks\n'
for a in "${apps[@]}"; do
  read -r id version _ <<<"$a"
  printf '%s-cli = { version = "%s", asset_pattern = "%s-cli-*-macos-universal.zip", os = ["macos"] }\n' "$id" "$version" "$id"
  printf '%s = { version = "%s", asset_pattern = "%s-*-macos-universal.dmg", os = ["macos"], postinstall = '"'"'sh "{{ config_root }}/scripts/unpack-dmg.sh"'"'"' }\n' "$id" "$version" "$id"
done

for a in "${apps[@]}"; do
  read -r id version name <<<"$a"
  cat <<EOF

[tasks."$id:install"]
description = "Install $name $version: its CLI ($id-cli, with the MCP server) and desktop app. Undo with $id:uninstall."
run = "mise run apps:install $id"

[tasks."$id:uninstall"]
description = "Uninstall $name: every installed version of its CLI and desktop app, unregistered from macOS."
run = "mise run apps:uninstall $id"
EOF
done
